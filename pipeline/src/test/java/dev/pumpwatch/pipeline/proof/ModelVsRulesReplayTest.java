package dev.pumpwatch.pipeline.proof;

import static org.assertj.core.api.Assertions.assertThat;

import dev.pumpwatch.common.Flag;
import dev.pumpwatch.common.Score;
import dev.pumpwatch.pipeline.proof.SystemProofTest.Out;
import dev.pumpwatch.pipeline.scorer.OnnxScorer;
import dev.pumpwatch.pipeline.scorer.RuleScorer;
import dev.pumpwatch.pipeline.scorer.Scorer;
import java.nio.file.Files;
import java.nio.file.Path;
import org.junit.jupiter.api.Test;

/**
 * Task 6.4: the same synthetic day through the full topology with the rule scorer and with the ONNX scorer.
 * Point {@code -Dpumpwatch.modelDir=...} at another model, and replace {@code SyntheticDay.generate()} with a
 * recording, to repeat this on real data. {@code -Dpumpwatch.writeReport=true} rewrites the markdown report.
 */
class ModelVsRulesReplayTest {
    static final String MODEL_DIR = System.getProperty("pumpwatch.modelDir", "src/test/resources/onnx-model/fixture-v1");
    static final Path REPORT = Path.of("..", "docs", "model-vs-rules-synthetic-day.md");

    private static double max(Out o, String ticker) {
        return o.scores().stream().filter(s -> s.ticker().equals(ticker)).mapToDouble(Score::score).max().orElse(Double.NaN);
    }

    private static boolean flagged(Out o, String ticker) {
        return o.flags().stream().map(Flag::ticker).anyMatch(ticker::equals);
    }

    @Test
    void modelServesAndDoesNotFlagTheNewsMoveOrTheQuietTicker() throws Exception {
        Scorer model = OnnxScorer.orRules(MODEL_DIR);
        assertThat(model).isInstanceOf(OnnxScorer.class);
        Out rules = SystemProofTest.firstRun();
        Out onnx = SystemProofTest.replay(SyntheticDay.generate(), model);

        assertThat(rules.scores()).isNotEmpty().allSatisfy(s -> assertThat(s.modelVersion()).isEqualTo(RuleScorer.VERSION));
        assertThat(onnx.scores()).isNotEmpty().allSatisfy(s -> {
            assertThat(s.modelVersion()).startsWith("onnx-");
            assertThat(s.score()).isBetween(0.0, 100.0);
        });
        assertThat(flagged(onnx, SyntheticDay.NEWS_MOVE)).isFalse();
        assertThat(flagged(onnx, SyntheticDay.QUIET)).isFalse();
        // the spec only asks for a comparison on the pump, so SYNP is reported, not asserted

        StringBuilder md = new StringBuilder("""
                # Model vs rules on the synthetic day

                Generated by `ModelVsRulesReplayTest` (task 6.4 of `add-pump-scoring-model`). This is a **synthetic day**
                (`SyntheticDay`: SYNP pump shape, SYNN news-backed move, SYNQ background) scored by a **fixture model**
                (`%s`, trained on `pumpml` synthetic data). It is not a real-data result and says nothing about live accuracy.
                Flags use the test pipeline settings (flag level 60, 5 minute window). To repeat on a recorded market day,
                point the same test at a recording and a real model.

                | Ticker | Role | Rules max score | Rules flagged | Model max score | Model flagged |
                |---|---|---|---|---|---|
                """.formatted(Path.of(MODEL_DIR).getFileName()));
        String[][] roles = {{SyntheticDay.PUMP, "pump, no catalyst"}, {SyntheticDay.NEWS_MOVE, "news-backed move"}, {SyntheticDay.QUIET, "background"}};
        for (String[] r : roles) {
            md.append("| %s | %s | %.1f | %s | %.1f | %s |\n".formatted(r[0], r[1], max(rules, r[0]),
                    flagged(rules, r[0]) ? "yes" : "no", max(onnx, r[0]), flagged(onnx, r[0]) ? "yes" : "no"));
        }
        md.append("\nModel version served: `%s`. Rules version: `%s`.\n".formatted(onnx.scores().get(0).modelVersion(), RuleScorer.VERSION));
        md.append("\nNote: both runs use the same flag level (60). The fixture model's calibrated score tops out at 56.4 on this day, "
                + "so it never reaches 60 and misses the pump. At the fixture's own tuned flag level (27.3) it would flag SYNP and "
                + "SYNN alike, because it scores both at 56.4. Neither is a finding about a real model.\n");
        System.out.println(md);
        if (Boolean.getBoolean("pumpwatch.writeReport")) Files.writeString(REPORT, md.toString());
    }
}
