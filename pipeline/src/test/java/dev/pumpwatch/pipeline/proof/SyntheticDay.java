package dev.pumpwatch.pipeline.proof;

import static dev.pumpwatch.pipeline.Fx.at;

import dev.pumpwatch.common.Json;
import dev.pumpwatch.common.Keys;
import dev.pumpwatch.common.PostRecord;
import dev.pumpwatch.common.SchemaVersions;
import dev.pumpwatch.common.SimHash;
import dev.pumpwatch.common.SourceHealth;
import dev.pumpwatch.common.Topics;
import dev.pumpwatch.pipeline.Fx;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.TreeMap;

/**
 * SYNTHETIC data, not market data: a deterministic 60 minute day for tickers SYNP, SYNN and SYNQ, generated by code
 * (no randomness, no recorded files) so schema bumps never leave it stale.
 *
 * <ul>
 *   <li>SYNP: pump shape at minute 10: eight new accounts post within a minute, heavy trades take 10.00 to 12.00,
 *       and no news or filing exists.
 *   <li>SYNN: the same price and volume spike at minute 40, but a news item lands first (minute 39) and chatter is
 *       quiet.
 *   <li>SYNQ: background only.
 * </ul>
 */
final class SyntheticDay {
    static final String PUMP = "SYNP", NEWS_MOVE = "SYNN", QUIET = "SYNQ";
    static final List<String> TICKERS = List.of(PUMP, NEWS_MOVE, QUIET);

    record Ev(String topic, String key, String value) {}

    private SyntheticDay() {}

    /** Events in event-time order. */
    static List<Ev> generate() {
        TreeMap<Instant, List<Ev>> tape = new TreeMap<>();
        // background: a quiet trade every 10 minutes per ticker, one post per ticker at minute 1
        for (int m = 0; m <= 60; m += 10) {
            for (String t : TICKERS) {
                String price = switch (t) {
                    case PUMP -> m >= 20 ? "12.00" : "10.00";
                    case NEWS_MOVE -> m >= 50 ? "24.00" : "20.00";
                    default -> "5.00";
                };
                add(tape, at(m, 0), Topics.TICKS, t, Fx.tick(at(m, 0), t, price, 100));
            }
        }
        for (int m = 1; m <= 1; m += 15) {
            for (String t : TICKERS) {
                add(tape, at(m, 30), Topics.RAW_POSTS, t, post(at(m, 30), t, "bg" + t, 365));
            }
        }
        // pump: 8 new accounts in under a minute, then 4 heavy trades climbing 10 to 12
        for (int i = 0; i < 8; i++) {
            Instant t = at(10, 0).plusSeconds(i * 7L);
            add(tape, t, Topics.RAW_POSTS, PUMP, post(t, PUMP, "pump" + i, 1));
        }
        spike(tape, PUMP, 10, "10.00", "10.60", "11.40", "12.00");
        // news-backed move: article first, same spike, ordinary chatter
        add(tape, at(39, 0), Topics.RAW_NEWS, NEWS_MOVE, Fx.news(at(39, 0), "synthetic-wire", NEWS_MOVE));
        for (int i = 0; i < 2; i++) {
            Instant t = at(40, 0).plusSeconds(i * 20L);
            add(tape, t, Topics.RAW_POSTS, NEWS_MOVE, post(t, NEWS_MOVE, "news" + i, 365));
        }
        spike(tape, NEWS_MOVE, 40, "20.00", "21.20", "22.80", "24.00");
        return tape.values().stream().flatMap(List::stream).toList();
    }

    /** A social-connector outage: reports "reddit" unhealthy from {@code from} and drops every post at or after it. */
    static List<Ev> withSocialOutage(List<Ev> day, Instant from) {
        List<Ev> out = new ArrayList<>();
        out.add(new Ev(Topics.SOURCE_HEALTH, "reddit", Json.toJson(new SourceHealth(1, from, from, "reddit", false, from))));
        for (Ev e : day) {
            boolean lost = e.topic().equals(Topics.RAW_POSTS)
                    && !Json.fromJson(e.value(), PostRecord.class).eventTime().isBefore(from);
            if (!lost) out.add(e);
        }
        return out;
    }

    private static void spike(TreeMap<Instant, List<Ev>> tape, String ticker, int minute, String... prices) {
        for (int i = 0; i < prices.length; i++) {
            Instant t = at(minute, 5).plusSeconds(i * 15L);
            add(tape, t, Topics.TICKS, ticker, Fx.tick(t, ticker, prices[i], 30_000));
        }
    }

    private static void add(TreeMap<Instant, List<Ev>> tape, Instant t, String topic, String key, String value) {
        tape.computeIfAbsent(t, k -> new ArrayList<>()).add(new Ev(topic, key, value));
    }

    private static String post(Instant when, String ticker, String author, int accountAgeDays) {
        String text = "synthetic chatter about $" + ticker + " from " + author;
        return Json.toJson(new PostRecord(SchemaVersions.POST, when, when.plusSeconds(1), "reddit",
                "syn-" + when.toEpochMilli() + author, Keys.authorKey(author), when.minusSeconds(accountAgeDays * 86400L),
                List.of(ticker), SimHash.of(text), null));
    }
}
